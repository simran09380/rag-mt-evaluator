from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


# ============================================================
# RETRIEVED EVIDENCE
# ============================================================

class EvidenceItem(BaseModel):
    id: str = Field(..., description="Unique evidence ID such as E1, E2")
    source: Optional[str] = Field(
        None,
        description="Source-language text associated with the evidence"
    )
    translation: Optional[str] = Field(
        None,
        description="Target-language translation associated with the evidence"
    )
    type: str = Field(
        ...,
        description="Evidence type: parallel_sentence, terminology, named_entity, etc."
    )
    relevance: Optional[float] = Field(
        None,
        description="Retrieval relevance score"
    )


class RetrievedEvidence(BaseModel):
    evidence: List[EvidenceItem] = Field(
        default_factory=list,
        description="Clean evidence provided to the LLM"
    )


# ============================================================
# TRADITIONAL METRICS
# ============================================================

class ReferenceBasedMetrics(BaseModel):
    bleu: Optional[float] = None
    chrf: Optional[float] = None
    chrf_plus_plus: Optional[float] = None
    meteor: Optional[float] = None
    ter: Optional[float] = None
    bertscore: Optional[float] = None
    comet: Optional[float] = None


class ReferenceFreeMetrics(BaseModel):
    multilingual_similarity: Optional[float] = None
    word_alignment_coverage: Optional[float] = None
    entity_preservation: Optional[float] = None
    terminology_accuracy: Optional[float] = None
    length_ratio: Optional[float] = None
    untranslated_token_ratio: Optional[float] = None


class MetricValues(BaseModel):
    reference_based: Optional[ReferenceBasedMetrics] = None
    reference_free: Optional[ReferenceFreeMetrics] = None


# ============================================================
# MODULE 8 INPUT
# ============================================================

class LLMEvaluationRequest(BaseModel):
    source: str = Field(
        ...,
        description="Original source sentence"
    )

    translation: str = Field(
        ...,
        description="Machine-translated output"
    )

    reference: Optional[str] = Field(
        None,
        description="Optional human reference translation"
    )

    source_lang: str = Field(
        ...,
        description="Source language"
    )

    target_lang: str = Field(
        ...,
        description="Target language"
    )

    domain: Optional[str] = Field(
        None,
        description="Translation domain such as healthcare"
    )

    retrieved_evidence: RetrievedEvidence = Field(
        default_factory=RetrievedEvidence,
        description="Evidence retrieved from Module 6"
    )

    metrics: Optional[MetricValues] = Field(
        None,
        description="Traditional metric values generated by Module 7"
    )

    evaluation_instructions: Optional[str] = Field(
        None,
        description="Additional instructions for the LLM evaluator"
    )


# ============================================================
# INDIVIDUAL EVALUATION JUDGMENT
# ============================================================

class EvaluationJudgment(BaseModel):
    score: float = Field(
        ...,
        description="Evaluation score"
    )

    judgment: str = Field(
        ...,
        description="Explanation of the evaluation"
    )

    evidence_ids: List[str] = Field(
        default_factory=list,
        description="Evidence IDs supporting this judgment"
    )


# ============================================================
# MODULE 8 OUTPUT
# ============================================================

class LLMEvaluationResult(BaseModel):
    accuracy: EvaluationJudgment

    fluency: EvaluationJudgment

    terminology: EvaluationJudgment

    named_entities: EvaluationJudgment

    factual_consistency: EvaluationJudgment

    style: EvaluationJudgment

    omissions: EvaluationJudgment

    additions: EvaluationJudgment


class LLMEvaluationResponse(BaseModel):
    evaluation: LLMEvaluationResult

    model: Optional[str] = None

    overall_score: Optional[float] = None

    supported_by_evidence: bool = True

    notes: Optional[str] = None