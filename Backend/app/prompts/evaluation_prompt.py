from typing import Optional


def build_evaluation_prompt(
    source: str,
    translation: str,
    source_lang: str,
    target_lang: str,
    domain: Optional[str] = None,
    reference: Optional[str] = None,
    evidence: Optional[list] = None,
    metrics: Optional[dict] = None,
    evaluation_instructions: Optional[str] = None,
) -> str:
    """
    Build the evidence-grounded prompt for the LLM evaluator.

    The LLM must evaluate the machine translation using only:
    - source sentence
    - machine translation
    - optional reference
    - retrieved evidence
    - traditional metric values
    - evaluation instructions
    """

    # --------------------------------------------------------
    # Optional sections
    # --------------------------------------------------------

    reference_section = (
        f"Reference translation:\n{reference}"
        if reference
        else "Reference translation:\nNot provided"
    )

    # --------------------------------------------------------
    # Retrieved evidence
    # --------------------------------------------------------

    if evidence:
        evidence_lines = []

        for item in evidence:
            evidence_id = item.get("id", "UNKNOWN")
            evidence_type = item.get("type", "unknown")
            relevance = item.get("relevance")

            source_text = item.get("source", "")
            translation_text = item.get("translation", "")

            relevance_text = (
                f" | relevance={relevance}"
                if relevance is not None
                else ""
            )

            evidence_lines.append(
                f"[{evidence_id}] "
                f"type={evidence_type}{relevance_text}\n"
                f"Source: {source_text}\n"
                f"Translation: {translation_text}"
            )

        evidence_section = "\n\n".join(evidence_lines)

    else:
        evidence_section = "No retrieved evidence provided."

    # --------------------------------------------------------
    # Metrics
    # --------------------------------------------------------

    if metrics:
        metrics_section = str(metrics)
    else:
        metrics_section = "No traditional metric values provided."

    # --------------------------------------------------------
    # Additional instructions
    # --------------------------------------------------------

    instructions_section = (
        evaluation_instructions
        if evaluation_instructions
        else "No additional evaluation instructions provided."
    )

    # --------------------------------------------------------
    # Final prompt
    # --------------------------------------------------------

    prompt = f"""
You are an expert machine translation evaluator.

Your task is to evaluate the machine-translated sentence using
ONLY the information provided in this prompt.

Do not use outside knowledge to invent errors or unsupported claims.

============================================================
TRANSLATION INFORMATION
============================================================

Source language: {source_lang}
Target language: {target_lang}
Domain: {domain or "Not specified"}

Source sentence:
{source}

Machine translation:
{translation}

{reference_section}

============================================================
RETRIEVED EVIDENCE
============================================================

The following evidence was retrieved from the translation
knowledge base.

Use the evidence only when it is relevant to the judgment.

{evidence_section}

============================================================
TRADITIONAL METRIC VALUES
============================================================

These values were generated by the previous evaluation module.

{metrics_section}

Metrics are supporting signals only.
Do not treat a metric score as proof of a specific linguistic
error.

============================================================
EVALUATION INSTRUCTIONS
============================================================

{instructions_section}

============================================================
EVALUATION CRITERIA
============================================================

Evaluate the machine translation on these eight dimensions:

1. Accuracy
   - Does the translation preserve the meaning of the source?

2. Fluency
   - Is the target-language output natural, grammatical,
     and readable?

3. Terminology
   - Are important domain-specific terms translated correctly?

4. Named Entities
   - Are names, organizations, places, products, people,
     and other named entities preserved or translated correctly?

5. Factual Consistency
   - Does the translation preserve the facts expressed in
     the source without introducing unsupported information?

6. Style
   - Is the translation appropriate for the source and domain?

7. Omissions
   - Identify information present in the source but missing
     from the machine translation.

8. Additions
   - Identify information introduced by the machine translation
     that is not supported by the source.

============================================================
IMPORTANT EVIDENCE-GROUNDING RULES
============================================================

1. Every substantive judgment must be supported by the source,
   reference, or retrieved evidence.

2. Include the IDs of the retrieved evidence items that support
   each judgment.

3. Do NOT invent evidence IDs.

4. If no retrieved evidence supports a judgment, use an empty
   evidence_ids list.

5. Do NOT report an error merely because the machine translation
   differs from the reference or retrieved translation.

6. A difference is not automatically an error.

7. Only report an omission when the source clearly contains
   information that is missing from the machine translation.

8. Only report an addition when the machine translation contains
   information that is not supported by the source.

9. Do not introduce facts, terminology, entities, or errors that
   are not supported by the provided information.

10. Traditional metrics are numerical signals and should not
    override direct evidence from the source and retrieved
    evidence.

11. If the evidence is insufficient to make a claim, state that
    the evidence is insufficient instead of guessing.

============================================================
SCORING
============================================================

Use a score from 1 to 5:

1 = Very poor
2 = Poor
3 = Acceptable / mixed
4 = Good
5 = Excellent

For omissions and additions:

- score 5 means no meaningful omission/addition is identified.
- lower scores indicate increasing severity.

============================================================
OUTPUT FORMAT
============================================================

Return ONLY valid JSON.

Do not include Markdown.
Do not include ```json.
Do not include explanations outside the JSON.

The JSON must have exactly this structure:

{{
  "evaluation": {{
    "accuracy": {{
      "score": 1-5,
      "judgment": "string",
      "evidence_ids": ["E1"]
    }},
    "fluency": {{
      "score": 1-5,
      "judgment": "string",
      "evidence_ids": []
    }},
    "terminology": {{
      "score": 1-5,
      "judgment": "string",
      "evidence_ids": []
    }},
    "named_entities": {{
      "score": 1-5,
      "judgment": "string",
      "evidence_ids": []
    }},
    "factual_consistency": {{
      "score": 1-5,
      "judgment": "string",
      "evidence_ids": []
    }},
    "style": {{
      "score": 1-5,
      "judgment": "string",
      "evidence_ids": []
    }},
    "omissions": {{
      "score": 1-5,
      "judgment": "string",
      "evidence_ids": []
    }},
    "additions": {{
      "score": 1-5,
      "judgment": "string",
      "evidence_ids": []
    }}
  }}
}}
"""

    return prompt.strip()